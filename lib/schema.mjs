import { transaction } from "./db.mjs";

export async function migrate() {
  await transaction(async (db) => {
    const id = db.sqlite
      ? "INTEGER PRIMARY KEY"
      : "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
    const tables = {
      users: `id ${id}, dni TEXT NOT NULL UNIQUE, name TEXT NOT NULL, email TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('admin','member','external')), active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)), password TEXT NOT NULL DEFAULT '!'`,
      attendance: `id ${id}, user_id INTEGER NOT NULL REFERENCES users(id), entered TEXT NOT NULL, exited TEXT`,
      visits: `id ${id}, host_id INTEGER NOT NULL REFERENCES users(id), name TEXT NOT NULL, reason TEXT NOT NULL, entered TEXT NOT NULL, exited TEXT`,
      items: `id ${id}, code TEXT NOT NULL UNIQUE, name TEXT NOT NULL, category TEXT NOT NULL, location TEXT NOT NULL, consumable INTEGER NOT NULL CHECK(consumable IN (0,1)), total INTEGER NOT NULL CHECK(total>=0), available INTEGER NOT NULL CHECK(available>=0), unavailable INTEGER NOT NULL DEFAULT 0 CHECK(unavailable>=0), minimum INTEGER NOT NULL DEFAULT 2 CHECK(minimum>=0), image TEXT NOT NULL DEFAULT '', active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)), CHECK(available+unavailable<=total)`,
      loans: `id ${id}, user_id INTEGER NOT NULL REFERENCES users(id), item_id INTEGER NOT NULL REFERENCES items(id), quantity INTEGER NOT NULL CHECK(quantity>0), returned INTEGER NOT NULL DEFAULT 0 CHECK(returned>=0 AND returned<=quantity), reason TEXT NOT NULL, due TEXT, created TEXT NOT NULL`,
      events: `id ${id}, actor_id INTEGER NOT NULL REFERENCES users(id), text TEXT NOT NULL, kind TEXT NOT NULL, created TEXT NOT NULL`,
      notifications: `id ${id}, event_id INTEGER NOT NULL REFERENCES events(id), recipient_id INTEGER NOT NULL REFERENCES users(id), read INTEGER NOT NULL DEFAULT 0 CHECK(read IN (0,1))`,
      mutations: `id ${id}, user_id INTEGER NOT NULL REFERENCES users(id), key TEXT NOT NULL, UNIQUE(user_id,key)`,
      mail_tasks: `id ${id}, user_id INTEGER NOT NULL REFERENCES users(id), created TEXT NOT NULL, sent TEXT, attempts INTEGER NOT NULL DEFAULT 0, lease TEXT`,
      sessions: `token TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id), expires TEXT NOT NULL`,
      access_tokens: `token TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id), expires TEXT NOT NULL`,
      rate_limits: `key TEXT PRIMARY KEY, attempts INTEGER NOT NULL, expires TEXT NOT NULL`,
      schema_versions: "version INTEGER PRIMARY KEY, applied TEXT NOT NULL",
    };
    for (const [table, columns] of Object.entries(tables))
      await db.query(`CREATE TABLE IF NOT EXISTS ${table} (${columns})`);
    for (const sql of [
      "CREATE UNIQUE INDEX IF NOT EXISTS users_email ON users(lower(email))",
      "CREATE UNIQUE INDEX IF NOT EXISTS one_open_attendance ON attendance(user_id) WHERE exited IS NULL",
      "CREATE INDEX IF NOT EXISTS loans_user ON loans(user_id)",
      "CREATE INDEX IF NOT EXISTS visits_host ON visits(host_id)",
      "CREATE INDEX IF NOT EXISTS notifications_recipient ON notifications(recipient_id)",
      "CREATE INDEX IF NOT EXISTS mail_created ON mail_tasks(created)",
    ])
      await db.query(sql);
    await db.query(
      "INSERT INTO schema_versions(version,applied) VALUES(1,?) ON CONFLICT(version) DO NOTHING",
      [new Date().toISOString()],
    );
  });
}
